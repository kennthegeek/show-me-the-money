/** Emit a readable, framework-native characterization test file from recorded cases. */

import { existsSync, readFileSync } from "node:fs";
import { basename, dirname, extname, join, relative } from "node:path";

import { toPosix } from "../core/files.ts";
import type { SafetyCase } from "./safetynet.ts";
import { ENCODER_SOURCE } from "./serialize.ts";

export type Framework = "vitest" | "jest" | "node";

export interface ProjectInfo {
  framework: Framework;
  esm: boolean;
}

export function detectProject(fromDir: string): ProjectInfo {
  for (let d = fromDir; ; d = dirname(d)) {
    const pkgPath = join(d, "package.json");
    if (existsSync(pkgPath)) {
      try {
        const pkg = JSON.parse(readFileSync(pkgPath, "utf8")) as {
          type?: string;
          dependencies?: Record<string, string>;
          devDependencies?: Record<string, string>;
        };
        const deps = { ...pkg.dependencies, ...pkg.devDependencies };
        const framework: Framework = deps.vitest ? "vitest" : deps.jest ? "jest" : "node";
        return { framework, esm: pkg.type === "module" };
      } catch {
        /* fall through */
      }
    }
    if (dirname(d) === d) return { framework: "node", esm: false };
  }
}

export interface GeneratedTests {
  testPath: string;
  testSource: string;
  supportPath: string;
  supportSource: string;
  included: number;
  skipped: number;
}

export function supportSource(): string {
  return `// Support code for characterization tests generated by Legacy-De-Spaghetti. Do not edit.
"use strict";
${ENCODER_SOURCE}
function pick(mod, name) {
  if (name === "<module>") return typeof mod === "function" ? mod : mod && mod.default;
  if (name === "default") return mod.default !== undefined ? mod.default : mod;
  if (mod && typeof mod[name] === "function") return mod[name];
  if (mod && mod.default && typeof mod.default[name] === "function") return mod.default[name];
  throw new Error("Export not found: " + name);
}
module.exports = { encode: __dsEncode, decode: __dsDecode, capture: __dsCapture, pick: pick };
`;
}

export function generateTests(
  sourceFile: string,
  cases: SafetyCase[],
  opts: { outDir: string; framework?: Framework; esm?: boolean; version: string },
): GeneratedTests {
  const project = detectProject(dirname(sourceFile));
  const framework = opts.framework ?? project.framework;
  const srcExt = extname(sourceFile);
  const isTs = /\.(c|m)?tsx?$/.test(srcExt);
  // vitest always speaks ESM; node:test follows the package type; jest stays CommonJS unless type=module.
  const esm = opts.esm ?? (framework === "vitest" || project.esm || srcExt === ".mjs" || srcExt === ".mts" || (isTs && framework === "node"));

  const testDir = opts.outDir ? join(dirname(sourceFile), opts.outDir) : dirname(sourceFile);
  const stem = basename(sourceFile, srcExt);
  const testExt = isTs && framework !== "node" ? ".ts" : esm && framework === "node" ? ".mjs" : ".js";
  const testPath = join(testDir, `${stem}.characterization.test${testExt}`);
  const supportPath = join(testDir, "_despaghetti.cjs");
  let importPath = toPosix(relative(testDir, sourceFile));
  if (!importPath.startsWith(".")) importPath = `./${importPath}`;

  const kept = cases.filter((c) => c.deterministic && c.outcome && !isTimeout(c));
  const skipped = cases.length - kept.length;
  const data = kept.map((c) => ({
    name: `${c.exportName === "<module>" ? "module" : c.exportName}: ${c.label}`,
    fn: c.exportName,
    args: c.args,
    expected: c.outcome,
    ...(c.argsAfter ? { argsAfter: c.argsAfter } : {}),
  }));

  const header = [
    `// Characterization tests generated by Legacy-De-Spaghetti v${opts.version}.`,
    `// They pin down what ${basename(sourceFile)} does *today*, quirks and bugs included, so a refactor`,
    "// can't change its behaviour without a failing test. Regenerate with:",
    `//   despaghetti safety-net ${toPosix(relative(process.cwd(), sourceFile))}`,
    ...(skipped ? [`// ${skipped} recorded case(s) were left out because their result was non-deterministic or timed out.`] : []),
    ...(isTs ? ["// @ts-nocheck"] : []),
  ];

  const imports = {
    vitest: esm
      ? [`import { describe, it, expect } from "vitest";`, `import ds from "./_despaghetti.cjs";`, `import * as subject from "${importPath}";`]
      : [],
    jest: esm
      ? [`import ds from "./_despaghetti.cjs";`, `import * as subject from "${importPath}";`]
      : [`const ds = require("./_despaghetti.cjs");`, `const subject = require("${importPath}");`],
    node: esm
      ? [`import { describe, it } from "node:test";`, `import assert from "node:assert/strict";`, `import ds from "./_despaghetti.cjs";`, `import * as subject from "${importPath}";`]
      : [`const { describe, it } = require("node:test");`, `const assert = require("node:assert/strict");`, `const ds = require("./_despaghetti.cjs");`, `const subject = require("${importPath}");`],
  }[framework];

  const eq = framework === "node" ? (a: string, b: string) => `assert.deepStrictEqual(${a}, ${b});` : (a: string, b: string) => `expect(${a}).toEqual(${b});`;

  const body = `
const cases = ${JSON.stringify(data, null, 2)};

describe(${JSON.stringify(`${basename(sourceFile)} (characterization)`)}, () => {
  for (const c of cases) {
    it(c.name, async () => {
      const args = ds.decode(c.args);
      const fn = ds.pick(subject, c.fn);
      const outcome = await ds.capture(() => fn(...args));
      ${eq("outcome", "c.expected")}
      if (c.argsAfter) ${eq("args.map((a) => ds.encode(a))", "c.argsAfter")}
    });
  }
});
`;
  return {
    testPath,
    testSource: `${[...header, "", ...imports].join("\n")}\n${body}`,
    supportPath,
    supportSource: supportSource(),
    included: kept.length,
    skipped,
  };
}

function isTimeout(c: SafetyCase): boolean {
  return "throws" in c.outcome && c.outcome.throws.name === "DespaghettiTimeout";
}
